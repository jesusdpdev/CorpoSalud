app.get('/api/asir/stats', authenticate, async (req, res) => {
  const anio = Number(req.query.anio);
  const mes = Number(req.query.mes);
  if (!Number.isInteger(anio) || !Number.isInteger(mes) || mes < 1 || mes > 12) {
    return res.status(400).json({ error: 'Año y mes no válidos' });
  }

  try {
    const [rows] = await pool.execute(
      `SELECT COUNT(DISTINCT h.id) AS totalCentros,
              COALESCE(SUM(CASE WHEN r.hospital_id IS NOT NULL THEN 1 ELSE 0 END), 0) AS reportesEnviados,
              COALESCE(SUM(CASE WHEN r.hospital_id IS NULL THEN 1 ELSE 0 END), 0) AS centrosSinReportar,
              0 AS conObservaciones
       FROM hospitales h
       LEFT JOIN (
         SELECT DISTINCT m.hospital_id
         FROM movimientos m
         JOIN periodos p ON p.id = m.periodo_id
         WHERE p.anio = ? AND p.mes = ?
       ) r ON r.hospital_id = h.id
       WHERE h.activo = 1`,
      [anio, mes]
    );
    res.json(rows[0]);
  } catch (err) {
    console.error('Error al consultar estadísticas ASIR:', err);
    res.status(500).json({ error: 'No se pudieron cargar las estadísticas' });
  }
});

app.get('/api/asir/ultimos-reportes', authenticate, async (req, res) => {
  const anio = Number(req.query.anio);
  const mes = Number(req.query.mes);
  const limit = Math.min(Math.max(Number(req.query.limit) || 8, 1), 50);
  if (!Number.isInteger(anio) || !Number.isInteger(mes) || mes < 1 || mes > 12) {
    return res.status(400).json({ error: 'Año y mes no válidos' });
  }

  try {
    const [rows] = await pool.execute(
      `SELECT h.id, h.nombre AS centro,
              MAX(m.updated_at) AS fecha_ultimo_reporte,
              COALESCE(SUM(CASE WHEN i.codigo = 'CONSULTAS' THEN m.valor END), 0) AS total_consultas,
              COUNT(DISTINCT m.indicador_id) AS indicadores_reportados,
              'validado' AS estado
       FROM movimientos m
       JOIN hospitales h ON m.hospital_id = h.id
       JOIN periodos p ON m.periodo_id = p.id
       JOIN indicadores i ON m.indicador_id = i.id
       WHERE p.anio = ? AND p.mes = ?
       GROUP BY h.id, h.nombre
       ORDER BY fecha_ultimo_reporte DESC
       LIMIT ?`,
      [anio, mes, limit]
    );
    res.json(rows);
  } catch (err) {
    console.error('Error al consultar últimos reportes:', err);
    res.status(500).json({ error: 'No se pudieron cargar los últimos reportes' });
  }
});


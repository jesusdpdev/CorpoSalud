// GET /api/asir/exportar/preview
app.get('/api/asir/exportar/preview', authenticate, async (req, res) => {
  const { anio, mes, tipo, hospital_id } = req.query;
  try {
    let query, params = [];
    if (tipo === 'reportes') {
      query = `SELECT h.nombre AS centro, h.codigo,
                 COUNT(DISTINCT m.indicador_id) AS indicadores,
                 SUM(m.valor) AS total
               FROM movimientos m
               JOIN hospitales h ON m.hospital_id = h.id
               JOIN periodos p ON m.periodo_id = p.id
               WHERE p.anio = ? AND p.mes = ?
               ${hospital_id ? 'AND m.hospital_id = ?' : ''}
               GROUP BY h.id, h.nombre, h.codigo`;
      params = hospital_id ? [anio, mes, hospital_id] : [anio, mes];
    } else if (tipo === 'movimientos') {
      query = `SELECT h.nombre AS hospital, s.nombre AS servicio,
                 i.nombre AS indicador, m.valor
               FROM movimientos m
               JOIN hospitales h ON m.hospital_id = h.id
               JOIN servicios s ON m.servicio_id = s.id
               JOIN indicadores i ON m.indicador_id = i.id
               JOIN periodos p ON m.periodo_id = p.id
               WHERE p.anio = ? AND p.mes = ?
               ${hospital_id ? 'AND m.hospital_id = ?' : ''}`;
      params = hospital_id ? [anio, mes, hospital_id] : [anio, mes];
    } else {
      query = `SELECT h.nombre AS hospital, ta.nombre AS tipo,
                 e.nombre AS especialidad, a.programadas, a.realizadas, a.cantidad
               FROM atenciones a
               JOIN hospitales h ON a.hospital_id = h.id
               JOIN tipos_atencion ta ON a.tipo_atencion_id = ta.id
               LEFT JOIN especialidades e ON a.especialidad_id = e.id
               JOIN periodos p ON a.periodo_id = p.id
               WHERE p.anio = ? AND p.mes = ?
               ${hospital_id ? 'AND a.hospital_id = ?' : ''}`;
      params = hospital_id ? [anio, mes, hospital_id] : [anio, mes];
    }
    const [rows] = await pool.query(query, params);
    res.json(rows);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

// GET /api/asir/alertas
app.get('/api/asir/alertas', authenticate, async (req, res) => {
  const { anio, mes } = req.query;
  try {
    await ensureAlertasContactosTable();
    const [rows] = await pool.query(
      `SELECT h.id, h.nombre AS centro, 'danger' AS tipo, 
              CONCAT('No ha enviado el reporte del mes ', ?, '/', ?) AS mensaje,
              CASE WHEN c.id IS NOT NULL THEN 1 ELSE 0 END AS contactado
       FROM hospitales h
       LEFT JOIN alertas_contactos c
         ON c.hospital_id = h.id AND c.anio = ? AND c.mes = ?
       WHERE h.activo = 1
         AND h.id NOT IN (
           SELECT DISTINCT m.hospital_id 
           FROM movimientos m
           JOIN periodos p ON m.periodo_id = p.id
           WHERE p.anio = ? AND p.mes = ?
         )`,
      [mes, anio, anio, mes, anio, mes]
    );
    res.json(rows);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

// POST /api/asir/alertas/:id/contactar
app.post('/api/asir/alertas/:id/contactar', authenticate, async (req, res) => {
  if (![1, 2, 3].includes(Number(req.user.rol_id))) {
    return res.status(403).json({ error: 'No tiene permiso para registrar contactos' });
  }

  const hospitalId = Number(req.params.id);
  const anio = Number(req.body.anio);
  const mes = Number(req.body.mes);
  if (!Number.isSafeInteger(hospitalId) || hospitalId < 1 ||
      !Number.isInteger(anio) || !Number.isInteger(mes) || mes < 1 || mes > 12) {
    return res.status(400).json({ error: 'Centro, año o mes no válidos' });
  }

  try {
    await ensureAlertasContactosTable();
    const [centros] = await pool.execute(
      'SELECT id FROM hospitales WHERE id = ? AND activo = 1',
      [hospitalId]
    );
    if (!centros.length) return res.status(404).json({ error: 'No se encontró el centro de salud' });

    if (pool.postgres) {
      await pool.execute(
        `INSERT INTO alertas_contactos (hospital_id, anio, mes, contactado_por)
         VALUES (?, ?, ?, ?)
         ON CONFLICT (hospital_id, anio, mes)
         DO UPDATE SET contactado_por = EXCLUDED.contactado_por, contactado_en = CURRENT_TIMESTAMP`,
        [hospitalId, anio, mes, req.user.id]
      );
    } else {
      await pool.execute(
        `INSERT INTO alertas_contactos (hospital_id, anio, mes, contactado_por)
         VALUES (?, ?, ?, ?)
         ON DUPLICATE KEY UPDATE contactado_por = VALUES(contactado_por)`,
        [hospitalId, anio, mes, req.user.id]
      );
    }
    return res.json({ ok: true, contactado: true });
  } catch (err) {
    console.error('Error al guardar contacto de alerta:', err);
    return res.status(500).json({ error: 'No se pudo guardar el contacto' });
  }
});


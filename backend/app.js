async function ensureAlertasContactosTable() {
  if (pool.postgres) {
    await pool.query(`
      CREATE TABLE IF NOT EXISTS alertas_contactos (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        hospital_id bigint NOT NULL,
        anio smallint NOT NULL,
        mes smallint NOT NULL,
        contactado_por bigint NOT NULL,
        contactado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT uq_alerta_contacto_periodo UNIQUE (hospital_id, anio, mes)
      )
    `);
    return;
  }
  await pool.query(`
    CREATE TABLE IF NOT EXISTS alertas_contactos (
      id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
      hospital_id BIGINT UNSIGNED NOT NULL,
      anio SMALLINT UNSIGNED NOT NULL,
      mes TINYINT UNSIGNED NOT NULL,
      contactado_por BIGINT UNSIGNED NOT NULL,
      contactado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
      UNIQUE KEY uq_alerta_contacto_periodo (hospital_id, anio, mes)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  `);
}


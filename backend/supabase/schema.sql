CREATE TABLE IF NOT EXISTS roles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(30) NOT NULL UNIQUE,
  nombre varchar(100) NOT NULL,
  descripcion text
);

CREATE TABLE IF NOT EXISTS municipios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS categorias_indicador (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(50) NOT NULL UNIQUE,
  nombre varchar(100) NOT NULL,
  orden integer DEFAULT 0
);

CREATE TABLE IF NOT EXISTS servicios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(20) NOT NULL UNIQUE,
  nombre varchar(100) NOT NULL,
  categoria varchar(50),
  activo smallint DEFAULT 1
);

CREATE TABLE IF NOT EXISTS especialidades (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(50) NOT NULL UNIQUE,
  nombre varchar(150) NOT NULL,
  activo smallint DEFAULT 1
);

CREATE TABLE IF NOT EXISTS tipos_atencion (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(50) NOT NULL UNIQUE,
  nombre varchar(150) NOT NULL,
  grupo varchar(30),
  activo smallint DEFAULT 1
);

CREATE TABLE IF NOT EXISTS periodos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  anio integer NOT NULL,
  mes integer NOT NULL,
  CONSTRAINT uq_anio_mes UNIQUE (anio, mes)
);

CREATE TABLE IF NOT EXISTS hospitales (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  municipio_id integer REFERENCES municipios(id),
  nombre varchar(200) NOT NULL,
  codigo varchar(200) NOT NULL UNIQUE,
  tipo varchar(50),
  nivel_complejidad varchar(20),
  activo smallint DEFAULT 1,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS indicadores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria_id integer REFERENCES categorias_indicador(id),
  codigo varchar(50) NOT NULL UNIQUE,
  nombre varchar(200) NOT NULL,
  descripcion text,
  unidad varchar(30),
  tipo_agregacion varchar(10) DEFAULT 'sum',
  por_servicio smallint DEFAULT 0,
  activo smallint DEFAULT 1
);

CREATE TABLE IF NOT EXISTS usuarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(200) NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  nombre varchar(200) NOT NULL,
  rol_id integer NOT NULL REFERENCES roles(id),
  activo smallint DEFAULT 1,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS hospital_servicios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id integer NOT NULL REFERENCES hospitales(id),
  servicio_id integer NOT NULL REFERENCES servicios(id),
  camas_operativas integer DEFAULT 0,
  activo smallint DEFAULT 1,
  CONSTRAINT uq_hospital_servicio UNIQUE (hospital_id, servicio_id)
);

CREATE TABLE IF NOT EXISTS movimientos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id integer NOT NULL REFERENCES hospitales(id),
  servicio_id integer REFERENCES servicios(id),
  indicador_id integer NOT NULL REFERENCES indicadores(id),
  periodo_id integer NOT NULL REFERENCES periodos(id),
  valor numeric(12, 2) NOT NULL,
  usuario_id integer,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_movimiento UNIQUE (hospital_id, servicio_id, indicador_id, periodo_id)
);

CREATE TABLE IF NOT EXISTS atenciones (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id integer NOT NULL REFERENCES hospitales(id),
  tipo_atencion_id integer NOT NULL REFERENCES tipos_atencion(id),
  periodo_id integer NOT NULL REFERENCES periodos(id),
  servicio_id integer REFERENCES servicios(id),
  especialidad_id integer REFERENCES especialidades(id),
  cantidad integer DEFAULT 0,
  programadas integer DEFAULT 0,
  realizadas integer DEFAULT 0,
  primeras integer DEFAULT 0,
  sucesivas integer DEFAULT 0,
  interconsultas integer DEFAULT 0,
  citados_ausentes integer DEFAULT 0,
  estudios_informados integer DEFAULT 0,
  placas_danadas integer DEFAULT 0,
  solicitadas_red integer DEFAULT 0,
  usuario_id integer,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_atencion UNIQUE (hospital_id, tipo_atencion_id, servicio_id, especialidad_id, periodo_id)
);

CREATE TABLE IF NOT EXISTS auditoria (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer REFERENCES usuarios(id),
  tabla varchar(50) NOT NULL,
  registro_id integer NOT NULL,
  accion varchar(20),
  valor_anterior jsonb,
  valor_nuevo jsonb,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS alertas_contactos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id bigint NOT NULL,
  anio smallint NOT NULL,
  mes smallint NOT NULL,
  contactado_por bigint NOT NULL,
  contactado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_alerta_contacto_periodo UNIQUE (hospital_id, anio, mes)
);

CREATE TABLE IF NOT EXISTS excel_importaciones (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria varchar(4) NOT NULL CHECK (categoria IN ('asir', 'asic')),
  nombre_archivo varchar(255) NOT NULL,
  importado_por bigint NOT NULL,
  creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  cantidad_hojas integer NOT NULL DEFAULT 0,
  hojas_omitidas integer NOT NULL DEFAULT 0,
  storage_path text NOT NULL
);

CREATE TABLE IF NOT EXISTS excel_importacion_hojas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  importacion_id bigint NOT NULL REFERENCES excel_importaciones(id) ON DELETE CASCADE,
  nombre_hoja varchar(255) NOT NULL,
  centro_nombre varchar(255) NOT NULL,
  anio smallint,
  rango_usado varchar(32),
  cantidad_celdas integer NOT NULL DEFAULT 0,
  celdas_json text NOT NULL,
  CONSTRAINT uq_excel_importacion_hoja UNIQUE (importacion_id, nombre_hoja)
);

CREATE INDEX IF NOT EXISTS idx_excel_categoria_fecha
  ON excel_importaciones (categoria, creado_en DESC);
CREATE INDEX IF NOT EXISTS idx_excel_hojas_importacion
  ON excel_importacion_hojas (importacion_id);
CREATE INDEX IF NOT EXISTS idx_hospitales_municipio
  ON hospitales (municipio_id);
CREATE INDEX IF NOT EXISTS idx_periodos_year
  ON periodos (anio);
CREATE INDEX IF NOT EXISTS idx_movimientos_periodo_hospital
  ON movimientos (periodo_id, hospital_id);
CREATE INDEX IF NOT EXISTS idx_atenciones_periodo_tipo
  ON atenciones (periodo_id, tipo_atencion_id);
